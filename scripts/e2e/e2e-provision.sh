#!/bin/bash
# Provision a disposable Immich instance for the e2e tests.
#
# The instance has its own compose project (immich-e2e) and its own container
# names. It never touches a developer's Immich install, and its API listens on
# loopback only.

set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

usage() {
  cat <<'EOF'
Usage: e2e-provision.sh [options]

Options:
  --force             replace an existing instance in the install directory
  --install-dir DIR   where to put the compose file and data
                      (default: internal/e2e/testdata/immich-server)
  --port PORT         loopback port for the API (default: 2283)
  --version TAG       Immich release for the compose file and the images
                      (default: v3.2.4)
  --no-rootless       run the containers as root (default: rootless)
  -h, --help          show this help

Rootless: the services run as the current uid/gid, with no-new-privileges and
NET_RAW dropped, as in Immich's docker-compose.rootless.yml. The bind mounts
stay owned by the developer.

Environment:
  E2E_PROJECT         compose project name (default: immich-e2e)
  E2E_INSTALL_DIR     same as --install-dir
  E2E_PORT            same as --port
  E2E_VERSION         same as --version
  E2E_ROOTLESS        true or false (default: true)
  E2E_UID, E2E_GID    uid/gid used by the containers (default: id -u, id -g)
EOF
}

force=false
while [ $# -gt 0 ]; do
  case "$1" in
    --force) force=true; shift ;;
    --install-dir) [ $# -ge 2 ] || e2e_die "--install-dir needs a value"; E2E_INSTALL_DIR="$2"; shift 2 ;;
    --port) [ $# -ge 2 ] || e2e_die "--port needs a value"; E2E_PORT="$2"; shift 2 ;;
    --version) [ $# -ge 2 ] || e2e_die "--version needs a value"; E2E_VERSION="$2"; shift 2 ;;
    --rootless) E2E_ROOTLESS=true; shift ;;
    --no-rootless) E2E_ROOTLESS=false; shift ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; e2e_die "unknown argument: $1" ;;
  esac
done
export E2E_PROJECT E2E_INSTALL_DIR E2E_PORT E2E_VERSION E2E_ROOTLESS E2E_UID E2E_GID

e2e_require_docker
e2e_require_cmd curl
e2e_require_cmd go

if [ -f "${E2E_INSTALL_DIR}/docker-compose.yml" ]; then
  if [ "${force}" != true ]; then
    e2e_die "${E2E_INSTALL_DIR} already holds an e2e instance.
       Re-run with --force to replace it, or remove it with scripts/e2e/e2e-cleanup.sh"
  fi
  e2e_info "removing the existing instance in ${E2E_INSTALL_DIR}"
  e2e_compose down --volumes --remove-orphans || true
  rm -rf "${E2E_INSTALL_DIR}" || e2e_die "could not remove ${E2E_INSTALL_DIR}; remove it manually"
fi

# Pre-create the bind mounts. With rootless containers the services write as the
# current user, so these directories must exist and belong to that user.
mkdir -p "${E2E_INSTALL_DIR}" \
  "${E2E_INSTALL_DIR}/library" \
  "${E2E_INSTALL_DIR}/postgres" \
  "${E2E_INSTALL_DIR}/ml-model-cache" \
  "${E2E_INSTALL_DIR}/redis"

# Download the compose file from the same release as the images, so the two
# cannot drift apart.
base_url="https://github.com/immich-app/immich/releases/download/${E2E_VERSION}"
e2e_info "downloading Immich ${E2E_VERSION} compose file and example environment"
curl -fsSL "${base_url}/docker-compose.yml" -o "${E2E_INSTALL_DIR}/docker-compose.yml" ||
  e2e_die "could not download ${base_url}/docker-compose.yml (unknown release ${E2E_VERSION}?)"
curl -fsSL "${base_url}/example.env" -o "${E2E_INSTALL_DIR}/.env" ||
  e2e_die "could not download ${base_url}/example.env"

# Pin the images to the release, whatever the example environment says.
if grep -q '^IMMICH_VERSION=' "${E2E_INSTALL_DIR}/.env"; then
  sed -i.bak -E "s|^IMMICH_VERSION=.*|IMMICH_VERSION=${E2E_VERSION}|" "${E2E_INSTALL_DIR}/.env"
  rm -f "${E2E_INSTALL_DIR}/.env.bak"
else
  printf '\nIMMICH_VERSION=%s\n' "${E2E_VERSION}" >>"${E2E_INSTALL_DIR}/.env"
fi

# Compose override: unique container names, API bound to loopback only, and,
# unless --no-rootless, the hardening of Immich's docker-compose.rootless.yml.
# !override (Compose >= 2.24) replaces the base list instead of appending.
{
  cat <<'YAML'
# Generated by scripts/e2e/e2e-provision.sh. Do not edit.
services:
  immich-server:
    container_name: ${E2E_PROJECT}_server
    ports: !override
      - "127.0.0.1:${E2E_PORT}:2283"
    # :z is ignored when SELinux is disabled, and needed when it is enabled.
    volumes: !override
      - ${UPLOAD_LOCATION}:/data:z
      - /etc/localtime:/etc/localtime:ro
YAML
  if [ "${E2E_ROOTLESS}" = true ]; then
    cat <<'YAML'
    user: "${E2E_UID}:${E2E_GID}"
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - NET_RAW
YAML
  fi
  cat <<'YAML'
  immich-machine-learning:
    container_name: ${E2E_PROJECT}_machine-learning
YAML
  if [ "${E2E_ROOTLESS}" = true ]; then
    cat <<'YAML'
    user: "${E2E_UID}:${E2E_GID}"
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - NET_RAW
    volumes: !override
      - ./ml-model-cache:/cache:z
YAML
  fi
  cat <<'YAML'
  redis:
    container_name: ${E2E_PROJECT}_redis
YAML
  if [ "${E2E_ROOTLESS}" = true ]; then
    cat <<'YAML'
    user: "${E2E_UID}:${E2E_GID}"
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - NET_RAW
    volumes: !override
      - ./redis:/data:z
YAML
  fi
  cat <<'YAML'
  database:
    container_name: ${E2E_PROJECT}_postgres
    volumes: !override
      - ${DB_DATA_LOCATION}:/var/lib/postgresql/data:z
YAML
  if [ "${E2E_ROOTLESS}" = true ]; then
    cat <<'YAML'
    user: "${E2E_UID}:${E2E_GID}"
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - NET_RAW
YAML
  fi
} >"${E2E_INSTALL_DIR}/docker-compose.e2e.yml"

e2e_info "pulling Immich ${E2E_VERSION} images (this may take a while on the first run)"
e2e_compose pull

e2e_info "starting the instance (project ${E2E_PROJECT}) on $(e2e_immich_url)"
e2e_compose up -d --force-recreate --remove-orphans

if ! e2e_wait_ready 300; then
  e2e_compose ps >&2 || true
  e2e_compose logs --tail=50 immich-server >&2 || true
  e2e_die "Immich did not answer on $(e2e_immich_url) within 300 seconds"
fi

"${E2E_SCRIPTS_DIR}/lib/e2e-provision-users.sh" "$(e2e_immich_url)" "${E2E_INSTALL_DIR}/e2eusers.env"

cat <<EOF

Immich ${E2E_VERSION} is ready.

  URL:          $(e2e_immich_url)
  Install dir:  ${E2E_INSTALL_DIR}
  Credentials:  ${E2E_INSTALL_DIR}/e2eusers.env (git-ignored, not printed)
  Compose:      project ${E2E_PROJECT}, containers ${E2E_PROJECT}_*

Run the e2e tests:

  e2e_url=$(e2e_immich_url) go test -v -tags=e2e -timeout=30m ./internal/e2e/client/

Reset the data between runs:

  ${E2E_SCRIPTS_DIR}/e2e-reset.sh

Remove the instance and its volumes:

  ${E2E_SCRIPTS_DIR}/e2e-cleanup.sh
EOF
